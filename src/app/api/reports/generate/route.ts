import { NextRequest, NextResponse } from 'next/server';
import { GoogleGenAI } from '@google/genai';
import { getGeminiApiKey } from '@/lib/config/env';
import { analyzeProjectDocuments } from '@/lib/ai/due-diligence-analyzer';
import { generateBuySellAdvisory } from '@/lib/ai/advisory-engine';
import {
  fetchExtendedStockDetail,
  searchCompaniesWithFY,
} from '@/lib/market/market-service';
import { addReport, getProjectById } from '@/lib/storage/app-storage';
import { ReportItem } from '@/types';
import { formatCurrency } from '@/lib/utils';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json().catch(() => ({}));
    const target = ((body.target as string) || '').trim();
    const reportType = ((body.type as ReportItem['type']) || 'IC Memo') as ReportItem['type'];
    const projectId = body.projectId as string | undefined;

    const project = projectId ? getProjectById(projectId) : undefined;
    const effectiveTarget = target || project?.ticker || project?.name || 'TCS';

    const [vdrAnalysis, stock, fyMatches] = await Promise.all([
      projectId ? analyzeProjectDocuments(projectId) : Promise.resolve(null),
      fetchExtendedStockDetail(effectiveTarget),
      searchCompaniesWithFY(effectiveTarget),
    ]);

    const advisory = await generateBuySellAdvisory({
      ticker: stock.ticker,
      stock,
      fyData: fyMatches[0] || null,
      vdrAnalysis,
    });

    const fy = fyMatches[0];
    const companyLabel = project?.name || stock.name || effectiveTarget;
    const tickerLabel = project?.ticker || stock.ticker || effectiveTarget.toUpperCase();

    const defaultTakeaways = [
      `Advisory Verdict: ${advisory.signalLabel} (${advisory.confidenceScore}% confidence) at current price ${formatCurrency(stock.price, 2, stock.currency)}.`,
      fy
        ? `Present FY Result (${fy.latestFYLabel}): ${fy.latestFYProfitOrLoss} on Revenue of ${fy.latestFYRevenue} (${fy.netMargin} net margin).`
        : `1Y Price Performance: ${stock.performance['1Y']}% vs benchmark at ${stock.peRatio}x P/E.`,
      vdrAnalysis
        ? `VDR Assessment Score: ${vdrAnalysis.investmentAssessment.overallScore}/100 across ${vdrAnalysis.documentNames.length} indexed PDF(s).`
        : `Key Risk Flag: ${advisory.riskFlags[0] || 'Standard market multiple sensitivity.'}`,
    ];

    let summary =
      vdrAnalysis?.investmentAssessment.overallThesis ||
      advisory.rationaleSummary;

    let keyTakeaways = defaultTakeaways;

    const apiKey = getGeminiApiKey();
    if (apiKey) {
      try {
        const aiClient = new GoogleGenAI({ apiKey });
        const prompt = `Generate a concise institutional ${reportType} summary for "${companyLabel}" (${tickerLabel}).
Context:
- Live Price: ${formatCurrency(stock.price, 2, stock.currency)}, P/E: ${stock.peRatio}x, Verdict: ${advisory.signalLabel} (${advisory.confidenceScore}%)
- Latest FY Financials: ${fy ? `${fy.latestFYRevenue} revenue, ${fy.latestFYProfitOrLoss}` : 'N/A'}
- VDR Due Diligence: ${vdrAnalysis ? vdrAnalysis.investmentAssessment.overallThesis : 'None uploaded'}

Return ONLY JSON: { "summary": "3-4 sentences", "keyTakeaways": ["bullet 1", "bullet 2", "bullet 3", "bullet 4"] }`;

        const res = await aiClient.models.generateContent({
          model: 'gemini-3-flash-preview',
          contents: prompt,
          config: { temperature: 0.2, responseMimeType: 'application/json' },
        });
        const parsed = JSON.parse(
          (res.text || '').replace(/^```json\s*/i, '').replace(/\s*```$/i, '')
        ) as { summary?: string; keyTakeaways?: string[] };
        if (parsed.summary) summary = parsed.summary;
        if (Array.isArray(parsed.keyTakeaways) && parsed.keyTakeaways.length > 0) {
          keyTakeaways = parsed.keyTakeaways;
        }
      } catch {
        // Keep deterministic grounded summary
      }
    }

    const verdict: ReportItem['verdict'] =
      advisory.action === 'Buy'
        ? 'Recommend Investment'
        : advisory.action === 'Sell'
        ? 'Pass - High Risk'
        : 'Hold for Better Entry';

    const markdownContent = `# ${reportType}: ${companyLabel} (${tickerLabel})
Generated by AURA Investment Copilot • ${new Date().toLocaleDateString('en-US', { month: 'short', day: '2-digit', year: 'numeric' })}

## Verdict: ${verdict} (${advisory.signalLabel} — ${advisory.confidenceScore}% Confidence)

## Executive Summary
${summary}

## Key Diligence Takeaways
${keyTakeaways.map((k) => `- ${k}`).join('\n')}

## Valuation & Live Market Snapshot
- Current Price: ${formatCurrency(stock.price, 2, stock.currency)}
- Target Price Range: ${formatCurrency(advisory.targetPriceLow, 2, stock.currency)} – ${formatCurrency(advisory.targetPriceHigh, 2, stock.currency)}
- P/E Ratio: ${stock.peRatio}x | Market Cap: ${stock.marketCap}
${fy ? `- Latest FY (${fy.latestFYLabel}): Revenue ${fy.latestFYRevenue} | ${fy.latestFYProfitOrLoss}` : ''}
`;

    const newReport: ReportItem = {
      id: `rep-${Date.now()}`,
      title: `${reportType}: ${companyLabel} (${tickerLabel})`,
      type: reportType,
      ticker: tickerLabel,
      company: companyLabel,
      author: 'AURA AI Copilot',
      date: new Date().toLocaleDateString('en-US', {
        month: 'short',
        day: '2-digit',
        year: 'numeric',
      }),
      readTime: '6 min read',
      status: 'Final',
      verdict,
      summary,
      keyTakeaways,
      markdownContent,
      projectId,
    };

    const reports = addReport(newReport);
    return NextResponse.json({ success: true, report: newReport, reports });
  } catch (error: unknown) {
    const msg = error instanceof Error ? error.message : 'Failed to generate report';
    return NextResponse.json({ success: false, error: msg }, { status: 500 });
  }
}
